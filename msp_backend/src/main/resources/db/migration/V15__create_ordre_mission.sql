-- Schema initial : _ordre_mission.
-- Correspond aux mappings JPA ; relations ajoutees dans V27.

create table _ordre_mission (
    id bigint generated by default as identity,
    date_creation timestamp(6) not null,
    date_modification timestamp(6),
    slug varchar(255) not null unique,
    creer_par varchar(255),
    modifier_par varchar(255),
    date_depart date not null,
    date_retour date not null,
    imputation_budgetaire varchar(255) not null,
    itineraire varchar(255) not null,
    libelle varchar(255) unique,
    moyen_deplacement varchar(255) not null,
    objet varchar(255) not null,
    observation varchar(255),
    valider_par bigint unique,
    ordre_mission_id bigint unique,
    primary key (id)
);

-- Schema initial : _document.
-- Correspond aux mappings JPA ; relations ajoutees dans V27.

create table _document (
    id bigint generated by default as identity,
    date_creation timestamp(6) not null,
    date_modification timestamp(6),
    slug varchar(255) not null unique,
    chemin varchar(255) not null,
    nom varchar(255) not null,
    taille bigint,
    type varchar(255),
    type_document varchar(255) not null check ((type_document in ('CONVOCATION','PV','ARCHIVE','DECAISSEMENT','COURRIER','PROFILE','CONJOINT','DESCENDANT','CERTIFICAT_VIE_COLLECTIF','RAPPORT_DE_MISSION','ACHAT','VENTE','CAS_SOCIAUX','PLAINTE','ORDRE_MISSION','ENCAISSEMENT'))),
    primary key (id)
);

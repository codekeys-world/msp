-- Schema initial : _courrier.
-- Correspond aux mappings JPA ; relations ajoutees dans V27.

create table _courrier (
    id bigint generated by default as identity,
    date_creation timestamp(6) not null,
    date_modification timestamp(6),
    slug varchar(255) not null unique,
    creer_par varchar(255),
    modifier_par varchar(255),
    date_arrivee date,
    date_depart date,
    description varchar(255) not null,
    nom varchar(255) unique,
    objet varchar(255) not null,
    type_courrier varchar(255) not null check ((type_courrier in ('ARRIVE','DEPART'))),
    valider_par bigint unique,
    courrier_id bigint unique,
    primary key (id)
);

-- Schema initial : _evenement.
-- Correspond aux mappings JPA ; relations ajoutees dans V27.

create table _evenement (
    id bigint generated by default as identity,
    date_creation timestamp(6) not null,
    date_modification timestamp(6),
    slug varchar(255) not null unique,
    action varchar(255),
    adresse_ip varchar(255),
    client varchar(255),
    date_evenement timestamp(6),
    utilisateur_id bigint,
    primary key (id)
);

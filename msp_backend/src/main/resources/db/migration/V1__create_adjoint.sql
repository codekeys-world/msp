-- Schema initial : _adjoint.
-- Correspond aux mappings JPA ; relations ajoutees dans V27.

create table _adjoint (
    id bigint generated by default as identity,
    date_creation timestamp(6) not null,
    date_modification timestamp(6),
    slug varchar(255) not null unique,
    date_debut date not null,
    date_fin date,
    est_actif boolean not null,
    motif varchar(255),
    role_delegue varchar(255) not null,
    adjoint_id bigint not null,
    delegant_id bigint not null,
    primary key (id)
);

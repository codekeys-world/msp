-- Schema initial : _encaissement.
-- Correspond aux mappings JPA ; relations ajoutees dans V27.

create table _encaissement (
    id bigint generated by default as identity,
    date_creation timestamp(6) not null,
    date_modification timestamp(6),
    slug varchar(255) not null unique,
    creer_par varchar(255),
    modifier_par varchar(255),
    date_debut_periode date,
    date_encaissement date not null,
    date_fin_periode date,
    montant bigint not null,
    observation varchar(255),
    type_budget varchar(255),
    type_encaissement varchar(255) not null check ((type_encaissement in ('VERSEMENT','DONS_LEG_INTERET'))),
    valider_par bigint unique,
    justificatif_id bigint unique,
    primary key (id)
);

create index idx_encaissement_situation 
   on _encaissement (date_encaissement, type_encaissement, montant);

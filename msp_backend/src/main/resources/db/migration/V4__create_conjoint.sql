-- Schema initial : _conjoint.
-- Correspond aux mappings JPA ; relations ajoutees dans V27.

create table _conjoint (
    id bigint generated by default as identity,
    date_creation timestamp(6) not null,
    date_modification timestamp(6),
    slug varchar(255) not null unique,
    creer_par varchar(255),
    modifier_par varchar(255),
    adresse varchar(255),
    date_naissance date,
    genre varchar(255) not null check ((genre in ('HOMME','FEMME'))),
    lieu_naissance varchar(255),
    nom varchar(255) not null,
    prenom varchar(255) not null,
    telephone_principal varchar(255) unique,
    telephone_secondaire varchar(255),
    valider_par bigint unique,
    acte_mariage_id bigint unique,
    adherent_id bigint,
    primary key (id)
);

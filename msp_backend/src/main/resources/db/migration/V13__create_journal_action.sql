-- Schema initial : _journal_action.
-- Correspond aux mappings JPA ; relations ajoutees dans V27.

create table _journal_action (
    id bigint generated by default as identity,
    date_creation timestamp(6) not null,
    date_modification timestamp(6),
    slug varchar(255) not null unique,
    action varchar(1000) not null,
    adresse_ip varchar(255) not null,
    client varchar(500) not null,
    date_action timestamp(6) not null,
    details varchar(2000),
    matricule varchar(255),
    module varchar(100),
    nom varchar(255) not null,
    prenom varchar(255) not null,
    role varchar(255) not null,
    statut varchar(255) not null,
    primary key (id)
);

create index idx_journal_date 
   on _journal_action (date_action);

create index idx_journal_role 
   on _journal_action (role);

create index idx_journal_module 
   on _journal_action (module);

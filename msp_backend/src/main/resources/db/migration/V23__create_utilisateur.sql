-- Schema initial : _utilisateur.
-- Correspond aux mappings JPA ; relations ajoutees dans V27.

create table _utilisateur (
    id bigint generated by default as identity,
    date_creation timestamp(6) not null,
    date_modification timestamp(6),
    slug varchar(255) not null unique,
    creer_par varchar(255),
    modifier_par varchar(255),
    adresse varchar(255),
    date_naissance date,
    genre varchar(255) not null check ((genre in ('HOMME','FEMME'))),
    lieu_naissance varchar(255),
    nom varchar(255) not null,
    prenom varchar(255) not null,
    telephone_principal varchar(255) unique,
    telephone_secondaire varchar(255),
    account_locked boolean not null,
    account_non_expired boolean not null,
    email varchar(255) unique,
    enabled boolean not null,
    matricule varchar(255) unique,
    mere varchar(255) not null,
    numero_adhesion varchar(255),
    numero_inscription varchar(255) not null unique,
    observations varchar(255),
    password TEXT not null,
    pere varchar(255) not null,
    valider_par bigint unique,
    profile_id bigint unique,
    role_id bigint,
    primary key (id)
);

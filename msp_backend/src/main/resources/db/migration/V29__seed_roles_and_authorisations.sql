INSERT INTO _role (date_creation, slug, nom)
SELECT current_timestamp, 'role-' || lower(nom), nom
FROM (VALUES
    ('ADMINISTRATEUR'),
    ('SECRETAIRE_ADMINISTRATIF'),
    ('PRESIDENT'),
    ('SECRETAIRE_ORGANISATION'),
    ('SECRETAIRE_AFFAIRE_SOCIALE'),
    ('TRESORIER'),
    ('COMMISSION_CONTROLE'),
    ('ADHERENT'),
    ('SYSADMIN')
) AS roles(nom)
ON CONFLICT (nom) DO NOTHING;

-- Acces complet pour les trois roles historiquement habilites.
INSERT INTO _role_authorisations (roles_id, authorisations_id)
SELECT r.id, a.id
FROM _role r CROSS JOIN _authorisation a
WHERE r.nom IN ('ADMINISTRATEUR', 'SECRETAIRE_ADMINISTRATIF', 'SYSADMIN')
  AND NOT EXISTS (SELECT 1 FROM _role_authorisations ra
                  WHERE ra.roles_id = r.id AND ra.authorisations_id = a.id);


-- Schema initial : _depense.
-- Correspond aux mappings JPA ; relations ajoutees dans V27.

create table _depense (
    id bigint generated by default as identity,
    date_creation timestamp(6) not null,
    date_modification timestamp(6),
    slug varchar(255) not null unique,
    creer_par varchar(255),
    modifier_par varchar(255),
    date_depense date not null,
    libelle varchar(255) not null,
    montant bigint not null,
    observation varchar(255),
    observation_validation varchar(255),
    statut varchar(255) not null check ((statut in ('EN_ATTENTE','VALIDEE','REJETEE'))),
    valider_par bigint unique,
    frais_de_gestion_id bigint not null,
    justificatif_id bigint unique,
    primary key (id)
);

create index idx_depense_date 
   on _depense (date_depense);

create index idx_depense_frais_statut 
   on _depense (frais_de_gestion_id, statut);

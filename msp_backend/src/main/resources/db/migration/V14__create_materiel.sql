-- Schema initial : _materiel.
-- Correspond aux mappings JPA ; relations ajoutees dans V27.

create table _materiel (
    id bigint generated by default as identity,
    date_creation timestamp(6) not null,
    date_modification timestamp(6),
    slug varchar(255) not null unique,
    creer_par varchar(255),
    modifier_par varchar(255),
    categorie varchar(255) not null,
    date_acquisition date,
    emplacement varchar(255) not null,
    fournisseur varchar(255) not null,
    nom varchar(255) not null,
    numero_serie varchar(255),
    observation varchar(255),
    prix_unitaire numeric(38,2) not null,
    quantite integer not null,
    statut varchar(255) not null check ((statut in ('ACTIF','EN_MAINTENANCE','HORS_SERVICE'))),
    valider_par bigint unique,
    primary key (id)
);

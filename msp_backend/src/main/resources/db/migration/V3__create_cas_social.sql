-- Schema initial : _cas_social.
-- Correspond aux mappings JPA ; relations ajoutees dans V27.

create table _cas_social (
    id bigint generated by default as identity,
    date_creation timestamp(6) not null,
    date_modification timestamp(6),
    slug varchar(255) not null unique,
    creer_par varchar(255),
    modifier_par varchar(255),
    date_cas date not null,
    duree_cotisation_mois integer,
    heures_hospitalisation integer,
    lien_defunt varchar(255) check ((lien_defunt in ('ADHERENT','PERE','MERE','EPOUX','EPOUSE','ENFANT'))),
    montant_cotisations_versees bigint,
    montant_prestation bigint,
    montant_remboursement bigint,
    nom_beneficiaire varchar(255),
    nom_defunt varchar(255),
    observation varchar(255),
    prenom_beneficiaire varchar(255),
    prenom_defunt varchar(255),
    statut_prestation varchar(255) check ((statut_prestation in ('PRESTATION','REMBOURSEMENT_COTISATIONS','NON_ELIGIBLE'))),
    telephone_beneficiaire varchar(255),
    type_beneficiaire varchar(255) not null check ((type_beneficiaire in ('ADHERENT','PARENTS','PERSONNE_DESIGNEE'))),
    type_cas varchar(255) not null check ((type_cas in ('MALADIE','ACCIDENT_CIRCULATION','RADIATION_REVOCATION_RETRAITE_DISCIPLINAIRE','DECES','REFORME_INVALIDITE','DECES_ADHERENT','RETRAITE'))),
    valider_par bigint unique,
    adherent_id bigint not null,
    justificatif_id bigint unique,
    primary key (id)
);
